import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const checkMode = process.argv.slice(2).includes('--check')
const unknownArgs = process.argv.slice(2).filter((arg) => arg !== '--check')

function requiredBrandText(value, label) {
  if (typeof value !== 'string' || value.trim() === '') {
    throw new Error(`branding/brand.json requires ${label}`)
  }
  if (/\r|\n/.test(value)) {
    throw new Error(`branding/brand.json ${label} must not contain a line break`)
  }
  return value
}

function escapeInnoPreprocessorString(value) {
  return value.replaceAll('"', '""')
}

function windowsInstallerBrand(brand) {
  const appName = requiredBrandText(brand.product?.names?.['en-US'], 'product.names.en-US')
  const publisher = requiredBrandText(brand.about?.teamName?.['en-US'], 'about.teamName.en-US')
  const publisherURL = requiredBrandText(brand.links?.website, 'links.website')

  return [
    '; Generated by scripts/sync-branding.mjs from branding/brand.json. Do not edit directly.',
    `#define BrandAppName "${escapeInnoPreprocessorString(appName)}"`,
    `#define BrandAppPublisher "${escapeInnoPreprocessorString(publisher)}"`,
    `#define BrandAppPublisherURL "${escapeInnoPreprocessorString(publisherURL)}"`,
    '',
  ].join('\n')
}

if (unknownArgs.length > 0) {
  console.error('Usage: node scripts/sync-branding.mjs [--check]')
  process.exitCode = 2
} else {
  const source = path.join(root, 'branding', 'brand.json')
  const brand = JSON.parse(await fs.readFile(source, 'utf8'))
  const asset = path.join(root, 'branding', brand.visual.logo.mark)

  const targets = [
    { source, destination: path.join(root, 'internal', 'brand', 'brand.json') },
    { source, destination: path.join(root, 'web', 'src', 'lib', 'brand.config.json') },
    { source, destination: path.join(root, 'mobile', 'src', 'brand.config.json') },
    { source: asset, destination: path.join(root, 'web', 'public', 'favicon.svg') },
    { source: asset, destination: path.join(root, 'landing', 'pudding-box-mark.svg') },
    { source, destination: path.join(root, 'landing', 'brand.config.json') },
    { source, destination: path.join(root, 'cmd', 'octo-relay', 'internal', 'push', 'brand.json') },
    { content: Buffer.from(windowsInstallerBrand(brand), 'utf8'), destination: path.join(root, 'packaging', 'windows', 'brand.iss') },
  ]

  if (checkMode) {
    const staleTargets = []
    for (const target of targets) {
      const expected = target.content ?? await fs.readFile(target.source)
      try {
        const actual = await fs.readFile(target.destination)
        if (!actual.equals(expected)) staleTargets.push(path.relative(root, target.destination))
      } catch (error) {
        if (error?.code === 'ENOENT') {
          staleTargets.push(path.relative(root, target.destination))
        } else {
          throw error
        }
      }
    }

    if (staleTargets.length > 0) {
      console.error('Brand generated targets are out of sync:\n' + staleTargets.map((target) => '- ' + target).join('\n') + '\nRun: node scripts/sync-branding.mjs')
      process.exitCode = 1
    } else {
      console.log('Brand generated targets are in sync (' + targets.length + ' targets checked).')
    }
  } else {
    for (const target of targets) {
      await fs.mkdir(path.dirname(target.destination), { recursive: true })
      if (target.content) {
        await fs.writeFile(target.destination, target.content)
      } else {
        await fs.copyFile(target.source, target.destination)
      }
    }
    console.log('Synced brand configuration and logo to ' + targets.length + ' generated targets.')
  }
}
